import { knock, solid } from '../solid'

// 毛线球：一个圆球（圆心 (12, 11)、半径 8.5）+ 球面上三道同一个方向绕过去的毛线（从左上的球边弯到右下的球边，一道比一道靠里）
// + 最里面那道毛线从球底绕出来，接着在地上拖出去一截线头（一笔画下来，到右下角 21.25）
// 靠「球面上一圈圈绕着的线 + 拖出去的线头」认出来；球类图标的缝线是对称的，也没有线头
// 圆从右端起笔、闭合：起笔点不挨着左边那道毛线的线头
const ball = 'M20.5 11A8.5 8.5 0 1 1 3.5 11A8.5 8.5 0 1 1 20.5 11Z'
// 三道毛线的端点都在球边上
const WRAPS = ['M9.4 2.91C14.5 4.5 18.5 8.5 20.09 13.6', 'M4.99 6.19C11 7.5 15.5 12 16.81 18.01']
const inner = 'M3.51 11.5C7.5 12.5 10.5 15.5 11.5 19.49'
const tail = 'C14 21.5 18 20 21.25 20.5'

export default () => [ball, ...WRAPS, `${inner}${tail}`]

// 实心：毛线球一块，三道毛线挖空——两端顺着线的方向多伸出一点、穿出球边，球面分成四瓣；线头照旧是线
const cut = (d, [ax, ay], [bx, by]) => `M${ax} ${ay}L${d.slice(1)}L${bx} ${by}`
export const fill = () => [
  solid(ball),
  knock([
    cut(WRAPS[0], [7.5, 2.3], [20.7, 15.5]),
    cut(WRAPS[1], [3, 5.75], [17.25, 20]),
    cut(inner, [1.5, 11], [12, 21.5]),
  ]),
  `M11.5 19.49${tail}`,
]
