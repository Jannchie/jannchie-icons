import { rounded } from '../geometry'
import { hole, knock, solid } from '../solid'

// 报纸：版面（7.5–20.5 × 3.5–20.5，左下角和左边的卷边相接）+ 左侧一条卷起来的边栏（3.5–7.5，底部半圆和版面底边连上）；
// 版面里一块标题框（10.5–17.5 × 6.5–10.5）和两行正文（13.5 / 16.5，第二行短一些）
// 竖线 3.5 / 7.5 / 10.5 / 17.5 / 20.5、横线 3.5 / 6.5 / 10.5 / 13.5 / 16.5 / 20.5 都落在 .5 上
export default ({ radius }) => [
  rounded([[5.5, 20.5], [20.5, 20.5], [20.5, 3.5], [7.5, 3.5], [7.5, 18.5]], radius, false),
  'M7.5 18.5A2 2 0 0 1 3.5 18.5V11.5A2 2 0 0 1 5.5 9.5H7.5',
  rounded([[10.5, 6.5], [17.5, 6.5], [17.5, 10.5], [10.5, 10.5]], Math.min(radius, 1)),
  'M10.5 13.5H17.5',
  'M10.5 16.5H15',
]

// 实心：版面和左边卷起的边栏各一块，两者之间的竖边挖开（上端缩一个线宽，不在外缘的内拐角咬出缺口）；
// 标题框挖成洞（洞外扩半个线宽后正好是描边版框的中心线），两行正文挖空
export const fill = ({ radius, stroke }) => {
  const h = stroke / 2
  return [
    solid([
      rounded([[7.5, 20.5], [20.5, 20.5], [20.5, 3.5], [7.5, 3.5]], radius),
      'M7.5 18.5A2 2 0 0 1 3.5 18.5V11.5A2 2 0 0 1 5.5 9.5H7.5Z',
      'M5.5 18.5H7.5V20.5H5.5Z',
    ]),
    knock(`M7.5 ${9.5 + stroke}V18.5`),
    hole(rounded([[10.5 + h, 6.5 + h], [17.5 - h, 6.5 + h], [17.5 - h, 10.5 - h], [10.5 + h, 10.5 - h]], Math.max(0, Math.min(radius, 1) - h))),
    knock(['M10.5 13.5H17.5', 'M10.5 16.5H15']),
  ]
}
