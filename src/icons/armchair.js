import { rounded } from '../geometry'
import { stacked } from '../solid'

// 扶手椅（正面）：和 sofa 同一套画法，座面只有一个人宽——扶手 4.5–8.5 / 15.5–19.5，靠背 6.5–17.5
export default ({ radius }) => [
  rounded([[4.5, 10.5], [8.5, 10.5], [8.5, 13.5], [15.5, 13.5], [15.5, 10.5], [19.5, 10.5], [19.5, 17.5], [4.5, 17.5]], Math.min(radius, 1.5)),
  rounded([[6.5, 10.5], [6.5, 4.5], [17.5, 4.5], [17.5, 10.5]], Math.min(radius, 2), false),
  'M6.5 17.5V19.5',
  'M17.5 17.5V19.5',
]

// 实心：靠背一块（往下伸到座面顶边，藏在扶手和座面后面），座面连扶手一块在前（和沙发一样）；靠背沿扶手和座面让出 GAP 的缝，
// 前面这块是完整的 U 形，不用挖线；椅腿照旧是线
export const fill = ({ radius }) => {
  const seat = rounded([[4.5, 10.5], [8.5, 10.5], [8.5, 13.5], [15.5, 13.5], [15.5, 10.5], [19.5, 10.5], [19.5, 17.5], [4.5, 17.5]], Math.min(radius, 1.5))
  return [
    ...stacked(rounded([[6.5, 13.5], [6.5, 4.5], [17.5, 4.5], [17.5, 13.5]], Math.min(radius, 2)), seat),
    'M6.5 17.5V19.5',
    'M17.5 17.5V19.5',
  ]
}
