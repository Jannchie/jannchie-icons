import { ray } from '../geometry'

// 烟花：在空中炸开的一朵——以 (12, 9.5) 为心往七个方向放射的火花（上、左、右、四个斜角，从半径 3 画到 6.5），
// 正下方那一道换成升空的尾迹：从炸点下面一直拖到 21.25
// 都是线，没有实心版
const [cx, cy] = [12, 9.5]

export default () => [
  ...[0, 45, 135, 180, 225, 270, 315].map(deg => ray([cx, cy], deg, 3, 6.5)),
  `M${cx} ${cy + 3}V21.25`,
]
