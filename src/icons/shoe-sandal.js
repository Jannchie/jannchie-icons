import { knock, solid } from '../solid'
// 人字拖（俯视）：脚印形的鞋底 + 从脚趾处分到两侧的人字带
export default () => [
  'M12 2.5C15.5 2.5 17.5 5.5 17.5 9.5C17.5 12.5 16.5 14 16.5 16.5C16.5 19.5 14.5 21.5 12 21.5C9.5 21.5 7.5 19.5 7.5 16.5C7.5 14 6.5 12.5 6.5 9.5C6.5 5.5 8.5 2.5 12 2.5Z',
  'M12 5.5L6.9 11',
  'M12 5.5L17.1 11',
]

// 实心：鞋底一块，人字带挖空；带子两端顺着带子方向穿出鞋底边，脚趾前端和后面的鞋底分成两块；
// 两条带子连成一条折线挖，尖角模式下顶点是斜接，不露出两个方线帽的台阶
export const fill = ({ stroke }) => {
  // 从 (12, 5.5) 到 (x, 11)，末端再往外伸 2 个线宽
  const end = (x) => {
    const [dx, dy] = [x - 12, 5.5]
    const k = 1 + 2 * stroke / Math.hypot(dx, dy)
    return `${12 + dx * k} ${5.5 + dy * k}`
  }
  return [
    solid('M12 2.5C15.5 2.5 17.5 5.5 17.5 9.5C17.5 12.5 16.5 14 16.5 16.5C16.5 19.5 14.5 21.5 12 21.5C9.5 21.5 7.5 19.5 7.5 16.5C7.5 14 6.5 12.5 6.5 9.5C6.5 5.5 8.5 2.5 12 2.5Z'),
    knock(`M${end(6.9)}L12 5.5L${end(17.1)}`),
  ]
}
