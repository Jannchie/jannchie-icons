import { crisp, rounded } from '../geometry'
import { block, WATER } from '../navy'
import { rotate } from '../transform'

// 航母：飞行甲板是一块贯通全长（3–21、13.5–16.5，厚 3：粗字重下板里也还空得出来）的平板，两头各伸出船体 2 格；
// 下面的船体明显收窄（16.5–19.5；舰尾 5、舰首从 19 斜切到 17），是闭合形状、顶边和飞行甲板底边重合（没有斜着接在甲板上的线头），没有炮塔；舰岛在中间偏舰尾（6–10），两级加桅杆（桅杆 x 9）；
// 舰首上方一架正在起飞的侧视喷气机，用细线（外框的 0.7 倍），离舰岛和甲板都留开：只画闭合轮廓（后掠垂尾、机背、尖机头、机腹，长 9.5），不画主翼，
// 以中心 (17, 6) 机头上扬 15°（机头到 21.4，机尾离舰岛桅杆 2.5，粗字重下也有缝）
const top = 13.5
const [px, py] = [17, 6]
const P = pts => pts.map(([u, v]) => [px + u, py + v])
const jet = { d: rotate(rounded(P([[-4.5, 0.5], [-5, -2.5], [-3.5, -2.5], [-2, -0.75], [2, -0.75], [4.5, 0.25], [2, 1], [-4.5, 1]]), 0.5), -15, [px, py]), thin: true }

export default ({ radius }) => [
  rounded([[3, top], [21, top], [21, 16.5], [3, 16.5]], crisp(radius)),
  rounded([[5, 16.5], [19, 16.5], [17, WATER], [5.5, WATER]], crisp(radius)),
  block(top, [[6, 9.5], [7, 9.5], [7, 7.5], [10, 7.5]], radius),
  'M9 7.5V3.5',
  jet,
]
