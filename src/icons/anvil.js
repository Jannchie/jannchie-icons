import { solid } from '../solid'

// 铁砧（侧视）：一整条轮廓——平直的砧面（3–20.5 在 4.5），左端收成一根长长的尖砧角（牛角），右端是方的砧尾（高 4）；
// 砧面下面收成细腰（10.5–15.5），再往下撇开成宽底座（7.5–18.5 × 15.5–19.5）。底座和细腰在砧身正下方，不在整个砧面的正中：
// 砧角伸出底座 4.5、砧尾只伸出 2，左右对称的话像一截工字钢
// 靠「一头尖一头方的砧面 + 细腰 + 宽底座」认出来；砧角的下沿是一条从细腰一路扬到角尖的弧
const body = (radius) => {
  const k = Math.min(radius, 1)
  return `M3 4.5H${20.5 - k}A${k} ${k} 0 0 1 20.5 ${4.5 + k}V${8.5 - k}A${k} ${k} 0 0 1 ${20.5 - k} 8.5H18`
    + 'C16.5 8.5 15.5 10 15.5 12C15.5 14 16.5 15.5 18.5 15.5'
    + `V${19.5 - k}A${k} ${k} 0 0 1 ${18.5 - k} 19.5H${7.5 + k}A${k} ${k} 0 0 1 7.5 ${19.5 - k}V15.5`
    + 'C9.5 15.5 10.5 14 10.5 12C10.5 9.5 7.5 7.5 3 4.5Z'
}

export default ({ radius }) => [body(radius)]

// 实心：整块铁砧一块
export const fill = ({ radius }) => [solid(body(radius))]
