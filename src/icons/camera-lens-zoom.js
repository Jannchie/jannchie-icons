import { lens } from '../lens'
import { knock, solid } from '../solid'

// 变焦镜头（侧视，前端朝右）：卡口 + 细的后段（半高 3.5）+ 台阶放大到粗的前段（半高 5.5，伸缩的变焦段），前端镜片外鼓 1.5；
// 前段上三道竖线是变焦环的防滑纹
export default ({ radius }) => [
  lens([[2.5, 9.5], [4.5, 9.5], [4.5, 8.5], [10.5, 8.5], [10.5, 6.5], [19.5, 6.5]], 1.5, radius),
  'M13.5 6.5V17.5M15.5 6.5V17.5M17.5 6.5V17.5',
]

// 实心：镜头填实，防滑纹挖成两道槽（三道间距 2，粗字重下槽会连成一片）；槽两端各离外缘一个线宽，镜筒不被切开
export const fill = ({ radius, stroke }) => [
  solid(lens([[2.5, 9.5], [4.5, 9.5], [4.5, 8.5], [10.5, 8.5], [10.5, 6.5], [19.5, 6.5]], 1.5, radius)),
  knock([13.5, 17.5].map(x => `M${x} ${6.5 + stroke}V${17.5 - stroke}`)),
]
