import { stacked } from '../solid'
import { mirror } from '../transform'

// 莲花（瑜伽、禅修、SPA 常用的那个符号）：五片尖头的花瓣从底下往上张开。正中一片竖直的（瓣尖 (12, 3.25)），两边各一片斜着的（瓣尖 (5, 6.5) / (19, 6.5)，被中间那片挡住一部分），
// 最外面各一片躺平的（瓣尖 (2.5, 12.25) / (21.5, 12.25)）；最外两片的下缘连成一条兜底的弧（最低 20），其余几片的边都落在这条弧上或前面一片的边上
// 一层压一层往两边张开的尖瓣 + 兜底的弧是莲花的记号：和 tulip（单朵带茎）、flower（俯视）区分开
const center = 'M10.5 19.9C8.25 14 9 7.5 12 3.25C15 7.5 15.75 14 13.5 19.9'
const side = 'M9.5 9.25C8.25 8 6.75 7 5 6.5C4.5 10.75 5.5 15.5 7.75 19'
const outer = 'M5.3 12.75C4.5 12.5 3.5 12.25 2.5 12.25C4 17 7.75 20 12 20C16.25 20 20 17 21.5 12.25C20.5 12.25 19.5 12.5 18.7 12.75'
const sides = [side, mirror(side)]

export default () => [center, ...sides, outer]

// 实心：最外一对（连着底）、中间一对、正中一片从后往前叠，每层在后面一层上让出缝
export const fill = () => stacked(`${outer}Z`, sides.map(d => `${d}Z`), `${center}Z`)
