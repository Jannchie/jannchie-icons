import { rounded } from '../geometry'

// 终点格子旗：长方形旗面（5.5–19.5 × 3.5–12.5）分成 4 × 2 格（每格 3.5 × 4.5），隔一格填实（格子再小，填实的格子连同描边会糊成一片）；旗杆从旗面左下角往下接到 21
const [x0, y0, w, h] = [5.5, 3.5, 3.5, 4.5]
// 填实的格子在和别的格子相邻的边上往里收 0.75（常规线宽的一半）：格子自身的描边会往外胀半个线宽，收进去以后黑白格才一样大；
// 靠旗面边框的边不收，直接和边框连成一片——留一道窄缝的话，粗字重下边框会被拥挤检测调细，旗杆的线头就盖不住了
const k = 0.75
function cell(i, j) {
  const [l, r] = [x0 + i * w + (i === 0 ? 0 : k), x0 + (i + 1) * w - (i === 3 ? 0 : k)]
  const [t, b] = [y0 + j * h + (j === 0 ? 0 : k), y0 + (j + 1) * h - (j === 1 ? 0 : k)]
  return { d: `M${l} ${t}H${r}V${b}H${l}Z`, fill: true }
}
// 旗面左边两个角不随全局圆角：旗杆的线头正好落在左下角上，角被圆角切掉时线头会被端点吸附拉歪
export default ({ radius }) => [
  rounded([[5.5, 3.5, 0], [19.5, 3.5], [19.5, 12.5], [5.5, 12.5, 0]], Math.min(radius, 1)),
  ...[[0, 0], [2, 0], [1, 1], [3, 1]].map(([i, j]) => cell(i, j)),
  'M5.5 12.5V21',
]
