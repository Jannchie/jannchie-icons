import { crisp, rounded } from '../geometry'
import { stacked } from '../solid'

// 围巾（正面，围在脖子上）：一圈月牙形的领圈（4.5–19.5，上沿在两头 3.5、中间兜下来贴着脖子到 6.5，下沿垂到 11），
// 领圈底下垂着两条围巾尾巴：右边一条（13.5–17.5，底在 18.5）、左边一条稍往左撇（7.5–11.5，底在 17.5），尾巴底下各两根流苏
// 两条尾巴的侧边都正好接在领圈下沿的中心线上（交点按曲线算好）；流苏是围巾的记号，和领带、项链区分开
const band = 'M4.5 3.5H7.5C8.5 5.5 10 6.5 12 6.5C14 6.5 15.5 5.5 16.5 3.5H19.5C18 8.5 15.5 11 12 11C8.5 11 6 8.5 4.5 3.5Z'
// 尾巴的侧边：右 (13.5, 8)–(14, 18.5)、(16.5, 6)–(17.5, 18.5)；左 (9, 8)–(7.5, 17.5)、竖直的 11.5
const tails = radius => [
  rounded([[13.633, 10.8, 0], [14, 18.5], [17.5, 18.5], [16.731, 8.884, 0]], Math.min(radius, 0.5), false),
  rounded([[8.673, 10.069, 0], [7.5, 17.5], [11.5, 17.5], [11.5, 10.983, 0]], Math.min(radius, 0.5), false),
]
// 流苏相距 1.75：细节线比主线细不了多少，靠得再近就糊成一片
const fringe = { d: 'M14.75 18.5V21M16.5 18.5V21M8.75 17.5V20M10.5 17.5V20', detail: true }

export default ({ radius }) => [band, ...tails(radius), fringe]

// 实心：两条尾巴各一块（顶上伸进领圈后面），领圈在前，尾巴在领圈四周让出缝；流苏照旧是线
const tailBlocks = radius => [
  rounded([[13.5, 8], [14, 18.5], [17.5, 18.5], [16.5, 6]], crisp(radius)),
  rounded([[9, 8], [7.5, 17.5], [11.5, 17.5], [11.5, 8]], crisp(radius)),
]
export const fill = ({ radius }) => [...stacked(tailBlocks(radius), band), fringe]
