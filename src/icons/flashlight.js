import { rounded } from '../geometry'
import { stacked } from '../solid'

// 手电筒（侧视，灯头朝右）：筒身（闭合，2.5–12.5 × 10–14）+ 外扩的灯头（闭合梯形，左边和筒身右边重合，右边 7–17 在 15.5）；
// 灯头前方三道光（从 18.5 起，离灯头 3）：中间那道水平，上下两道斜着散开
export default ({ radius }) => [
  rounded([[2.5, 10], [12.5, 10], [12.5, 14], [2.5, 14]], Math.min(radius, 1)),
  rounded([[12.5, 10], [15.5, 7], [15.5, 17], [12.5, 14]], Math.min(radius, 0.5)),
  'M18.5 12H21.5',
  'M18.5 8L21.5 6',
  'M18.5 16L21.5 18',
]

// 实心：筒身、灯头各一块完整的形状，灯头在前，筒身沿灯头让出 GAP 的缝（见 solid.js 的 stacked）——挖掉共用的那条边的话，
// 线帽停在灯头的两个拐角上，只擦着外缘，筒身和灯头之间留两道细桥；三道光照旧是线
export const fill = ({ radius }) => [
  ...stacked(
    rounded([[2.5, 10], [12.5, 10], [12.5, 14], [2.5, 14]], Math.min(radius, 1)),
    rounded([[12.5, 10], [15.5, 7], [15.5, 17], [12.5, 14]], Math.min(radius, 0.5)),
  ),
  'M18.5 12H21.5',
  'M18.5 8L21.5 6',
  'M18.5 16L21.5 18',
]
