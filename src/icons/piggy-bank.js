import { eye, softEar } from '../scene'

// 存钱罐（侧视、猪鼻朝右）：圆润的椭圆猪身（中心 (10.75, 12.25)、半轴 7.5 × 5.5）+ 头顶一只软耳朵 + 右边圆角的短猪鼻 +
// 两条敦实的短腿（宽 2，落到 19.75），连成一条外轮廓 + 背上的投币口 + 眼睛；不画硬币和尾巴，保持简洁
// 猪身左沿 3.25、猪鼻前端 20.75：墨迹左右居中；耳尖到腿底 3.75–19.75，上下也居中
const [cx, cy, rx, ry] = [10.75, 12.25, 7.5, 5.5]
const r3 = v => +v.toFixed(3)
// 猪身上 x 处的上 / 下沿、y 处的右沿
const topAt = x => r3(cy - ry * Math.sqrt(1 - ((x - cx) / rx) ** 2))
const bottomAt = x => r3(cy + ry * Math.sqrt(1 - ((x - cx) / rx) ** 2))
const rightAt = y => r3(cx + rx * Math.sqrt(1 - ((y - cy) / ry) ** 2))
// 整只猪是一条连续的外轮廓：从猪身左端顺时针沿椭圆走，经过耳朵、猪鼻、两条腿时绕出去再接回椭圆，
// 交接处椭圆不穿过耳朵、猪鼻和腿里面（只留剪影）；投币口和眼睛单独画
const arc = (x, y) => `A${rx} ${ry} 0 0 1 ${x} ${y}`
// 短腿：从右边那条竖边落到 18.75，底边圆角，再从左边竖边回到猪身（顺时针走的方向是从右往左）
const leg = (x0, x1) => `L${x1} ${bottomAt(x1)}V18.75A1 1 0 0 1 ${x0 + 1} 19.75A1 1 0 0 1 ${x0} 18.75V${bottomAt(x0)}`
export default () => [
  `M${cx - rx} ${cy}${arc(12.75, topAt(12.75))}`
  // 耳朵：耳根在猪身上沿 x 12.75 和 16.75，耳尖 (15.75, 3.75)
  + softEar([12.75, topAt(12.75)], [15.75, 3.75], [16.75, topAt(16.75)], 1.15)
  // 猪鼻：从猪身右沿伸出，上下 10.75–13.75，前端圆角
  + `${arc(rightAt(10.75), 10.75)}H19.75A1 1 0 0 1 20.75 11.75V12.75A1 1 0 0 1 19.75 13.75H${rightAt(13.75)}`
  + `${arc(15.75, bottomAt(15.75))}${leg(13.75, 15.75)}`
  + `${arc(7.75, bottomAt(7.75))}${leg(5.75, 7.75)}`
  + `${arc(cx - rx, cy)}Z`,
  'M8.75 9.75H11.75',
  eye(15.25, 10.75),
]
