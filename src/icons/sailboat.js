import { crisp, rounded } from '../geometry'

// 帆船（侧视、船首朝右）：一面大三角帆（竖边就是桅杆 x = 10.5，帆脚 10.5–19 × 14，和甲板隔 3，粗字重下也不粘）+ 桅杆落到甲板 +
// 上宽下窄的梯形船体（甲板 3–21 × 17，船底 6–18 × 20.5）；只留一面帆，比主帆加前帆简洁
export default ({ radius }) => [
  rounded([[3, 17], [21, 17], [18, 20.5], [6, 20.5]], crisp(radius)),
  // 桅杆和帆一笔画：从甲板沿桅杆上到帆顶，斜下到帆脚，再横回桅杆；帆顶是转角，尖角模式下不会被方头线帽顶出去
  rounded([[10.5, 17], [10.5, 3.5], [19, 14], [10.5, 14]], crisp(radius), false),
]
