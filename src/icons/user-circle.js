import { circle } from '../geometry'
import { hole, solid } from '../solid'

// 用户头像（圆框）：圆环（圆心 (12, 12)、半径 9）里一个头 + 肩膀
// 肩膀弧两端落在圆环上（y 17.5）：肩膀弧 + 圆环下面那一小段围成一块闭合形状，圆环上面的大弧从这块的两个角接出去——
// 拐角处都是同一条线顺着延续，没有线头斜接在圆环上（尖角模式下不会冒头）
export default () => [
  circle(12, 9.5, 3),
  'M4.876 17.500A11.400 11.400 0 0 1 19.124 17.500A9 9 0 0 1 4.876 17.500Z',
  'M4.876 17.500A9 9 0 1 1 19.124 17.500',
]

// 实心：圆盘一块，人像挖空：头挖成圆洞（洞外扩半个线宽后和描边版头的外缘一样大），
// 肩膀挖到圆环内缘为止（洞的下沿是半径 9 − 线宽的圆，外扩后离圆环中心线半个线宽，留下一圈和描边版一样宽的圆环）
export const fill = ({ stroke }) => {
  // 肩膀弧（圆心 (12, 26.4)、半径 11.4）和半径 9 − stroke 的圆的交点
  const [d, R, r] = [14.4, 11.4, 9 - stroke]
  const a = (d * d + r * r - R * R) / (2 * d)
  const x = Math.sqrt(r * r - a * a)
  return [
    solid(circle(12, 12, 9)),
    hole([circle(12, 9.5, 3), `M${12 - x} ${12 + a}A${R} ${R} 0 0 1 ${12 + x} ${12 + a}A${r} ${r} 0 0 1 ${12 - x} ${12 + a}Z`]),
  ]
}
