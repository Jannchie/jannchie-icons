import { frame } from '../geometry'
import { knock, solid } from '../solid'

// X 光片：一张方的片子（墨迹 3–21，线宽变粗往里长）+ 片子上一只手的骨头（伦琴那张最出名的 X 光片）
// 手骨全是分段的短线：食指、中指、无名指各一段掌骨 + 一段指骨（指根处断开一道关节缝），小指、拇指短一些，腕下两截前臂骨
// 掌骨下端 9.75 / 12 / 14.25 间隔 2.25，拇指、小指再往外让开，粗线的实心版里白线也不粘；中指 12 竖直，两边的手指稍稍张开
// 每道关节缝（同一根手指上下两段的端点）中心距都 ≥ 2，常规线宽下留得出缝
// 一节一节断开的骨头是记号：完整的手是 hand，断成关节的手骨只在 X 光片上见得到。
// 画成胸片（脊柱 + 肋骨）时读成一棵树、一个汉字；片子里放 bone 那根狗骨头，读成宠物零食
const bones = [
  'M9.75 15L9.25 11.5', 'M9 9.5L8.5 6.5',
  'M12 15V11', 'M12 9V6',
  'M14.25 15L14.75 11.5', 'M15 9.5L15.5 6.75',
  'M16.5 16L17.1 13.75', 'M17.65 11.75L17.9 10.75',
  'M8.25 16.75L7.45 14.9', 'M6.65 13.05L6.35 12.2',
  'M10.5 17V18', 'M13.5 17V18',
]
const film = (radius, stroke) => frame(stroke, Math.min(radius, 2), [3, 3, 21, 21])

export default ({ radius, stroke }) => [film(radius, stroke), ...bones]

// 实心：片子一块黑底，手骨挖成白线——就是 X 光片本来的样子
export const fill = ({ radius, stroke }) => [solid(film(radius, stroke)), knock(bones)]
