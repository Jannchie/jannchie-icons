import { rounded } from '../geometry'
import { dot } from '../scene'

// 游泳：小人趴在水面上往右游（头点 3，同 run 的头身比例）。身体从肩 (14, 11.5) 斜向左下到脚 (4, 14)；
// 前臂从肩向上划出一个弯（肘 (12.5, 7.5) → 手 (17.5, 6)）；头在肩的右前方；下面两道波浪线是水面
// 波浪：三段半波，每段宽 6、起伏 ±1.5（解析器不认 S，写成显式 C）
const wave = y => `M3 ${y}C5 ${y - 1.5} 7 ${y - 1.5} 9 ${y}C11 ${y + 1.5} 13 ${y + 1.5} 15 ${y}C17 ${y - 1.5} 19 ${y - 1.5} 21 ${y}`
export default ({ radius }) => [
  dot(17.5, 10.5, 3),
  rounded([[4, 14], [14, 11.5], [12, 7.5], [16.5, 5.5]], Math.min(radius, 1), false),
  wave(17.5),
  wave(21),
]
