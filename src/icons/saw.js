import { rounded } from '../geometry'

// 手锯（侧视，锯尖朝右）：手柄是带握孔的闭合块（2.5–10.5 × 5.5–15.5，握孔 5.5–7.5 × 8.5–12.5，四周离手柄边各 3）；
// 锯片也是闭合轮廓：上沿从手柄右边斜伸到锯尖，下沿是四个锯齿（齿距 2.5、齿高 1.5，从锯尖排到 11，不伸进手柄）
const teeth = Array.from({ length: 4 }, (_, i) => [[19.75 - i * 2.5, 17], [18.5 - i * 2.5, 15.5]]).flat()
export default ({ radius }) => [
  rounded([[2.5, 5.5], [10.5, 5.5], [10.5, 15.5], [2.5, 15.5]], Math.min(radius, 1.5)),
  rounded([[5.5, 8.5], [7.5, 8.5], [7.5, 12.5], [5.5, 12.5]], Math.min(radius, 0.5)),
  rounded([[10.5, 7.5], [21.5, 10], [21, 15.5], ...teeth, [10.5, 15.5]], Math.min(radius, 0.5)),
]
