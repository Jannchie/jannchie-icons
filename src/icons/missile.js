import { crisp, rounded } from '../geometry'

// 导弹：侧视、弹头朝右的细长弹体（2.5–21.5，上下边 9.5 / 14.5，中线 y = 12），弹头 5 格收尖；
// 弹体中部一对弹翼（10.5–14.5）、尾部一对较大的尾翼，上下对称；弹翼都是闭合形状，底边和弹体的边重合——没有斜着落在弹体上的线头；
// 中段弹翼和尾翼之间留 3，粗字重下也分得开；尖端不随全局圆角
const fin = (pts, radius) => rounded(pts, Math.min(radius, 0.5))
export default ({ radius }) => [
  rounded([[3.5, 9.5], [16.5, 9.5], [21.5, 12, crisp(radius)], [16.5, 14.5], [3.5, 14.5]], Math.min(radius, 1)),
  fin([[10.5, 9.5], [12, 6.5], [14, 6.5], [14.5, 9.5]], radius),
  fin([[10.5, 14.5], [12, 17.5], [14, 17.5], [14.5, 14.5]], radius),
  fin([[3.5, 9.5], [2.5, 4.5], [5, 4.5], [7.5, 9.5]], radius),
  fin([[3.5, 14.5], [2.5, 19.5], [5, 19.5], [7.5, 14.5]], radius),
]
