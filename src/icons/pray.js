import { rounded } from '../geometry'
import { mirror, rotate } from '../transform'

// 合十（祈祷、拜托、谢谢）：两只手从左下、右下斜着伸上来，指尖在正中顶上相碰，手腕插进转 45° 的袖口
// - 外轮廓一笔：左手腕 → 指关节（3.25, 12.5）→ 指尖（11, 3，圆角）→ 正中两个指尖之间的小凹口（12, 4.75）→ 右手镜像
// - 倒 V 是两只手四指的内侧边，和外边平行（并拢的四指是一条斜带），顶在（12, 7.25），这样倒 V 差不多正对着拇指圆头的圆心落下去，接得干脆
// - 两根大拇指是竖着的 U（7.5–10.5，宽 3、圆头半径 1.5，同 hand 的手指），立在两只手中间、挡在四指前面：倒 V 落在拇指圆头上为止；
//   拇指外侧那道竖线是拇指和手掌的分界，内侧边往下接手腕内侧，斜着落到袖口顶边上
// - 指关节放到 3.25（比 4.5 往外）是为了给拇指让位：拇指圆头离外边的中线留够 2，粗体也不粘
// 认出是两只手靠的是：顶上两个指尖之间的凹口 + 中间并排的两根拇指 + 两边各一截袖口；
// 只画两片叶形手掌（没有拇指）时读成羽毛、滑雪板；正面合成一个轮廓、正中一道缝时读成拱窗、帐篷；
// 侧面一前一后两只 hand 叠着（emoji 那种）在 24px 读成挥手、鼓掌
const APEX = [12, 7.25]
const THUMB = [9, 11]
// 左手四指内侧边：过 APEX、和外边（3.25, 12.5）→（11, 3）平行，落在左拇指圆头上的点
const leg = (() => {
  const [dx, dy] = [-7.75, 9.5].map(v => v / Math.hypot(7.75, 9.5))
  const [fx, fy] = [APEX[0] - THUMB[0], APEX[1] - THUMB[1]]
  const b = fx * dx + fy * dy
  const t = -b - Math.sqrt(b * b - (fx * fx + fy * fy - 1.5 * 1.5))
  return [APEX[0] + dx * t, APEX[1] + dy * t].map(v => +v.toFixed(3))
})()
// 手腕外边、内边都落在袖口顶边上（袖口顶边是过 (7.06, 16.94) 的 45° 线：y = x + 9.88）
const outline = rounded([[5.56, 15.44], [3.25, 12.5, 2], [11, 3, 1.25], [12, 4.75], [13, 3, 1.25], [20.75, 12.5, 2], [18.44, 15.44]], 0, false)
const vee = rounded([leg, [...APEX, 1], [24 - leg[0], leg[1]]], 0, false)
const thumb = 'M7.5 15V11A1.5 1.5 0 0 1 10.5 11V15.5L8.66 18.54'
// 袖口：6 × 3 的圆角方块绕自己的中心 (6, 18) 转 45°，跟着往外撇的小臂
const cuff = radius => rotate(rounded([[3, 16.5], [9, 16.5], [9, 19.5], [3, 19.5]], Math.min(radius, 1)), 45, [6, 18])

// 都是线，没有实心版（同 hand、clap）：填实后拇指和四指并成一块，拇指外侧那道线只能挖成死胡同的缝，又读回两片羽毛
export default ({ radius }) => [outline, vee, ...[thumb, cuff(radius)].flatMap(d => [d, mirror(d)])]
