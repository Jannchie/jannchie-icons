import { knock, solid } from '../solid'

// 松果：倒挂着的一颗——上头圆、往下收成尖的蛋形（6–18 × 5.5–21.25）+ 顶上一小截果柄（到 2.5）+ 身上三排一片压一片的鳞片：
// 每排是几道往下兜的弧，弧和弧接成朝上的尖；下一排的尖正好顶在上一排弧的最低点上（第一排两片，第二排中间一片、两边各半片，第三排两片），两头落在轮廓上
// 一片压一片的鳞片 + 往下收尖的蛋形是松果的记号：和戴帽子的 acorn、斜纹加叶冠的 pineapple 区分开
const body = 'M12 5.5C15.5 5.5 18 8 18 11.5C18 15.5 15.5 19 12 21.25C8.5 19 6 15.5 6 11.5C6 8 8.5 5.5 12 5.5Z'
// 每排：[左端, 中间的弧, 右端]；ENDS 是实心版顺着弧的方向往轮廓外多挖出去的两个端点
const ROWS = [
  ['6.3 9.5', 'Q9 13.5 12 8.5Q15 13.5 17.7 9.5', ['5.45 8.25', '18.55 8.25']],
  ['6.1 13', 'Q7.25 14.5 8.75 11.3Q12 18 15.25 11.3Q16.75 14.5 17.9 13', ['5.2 11.8', '18.8 11.8']],
  ['7.4 16.5', 'Q9.75 19.5 12 14.65Q14.25 19.5 16.6 16.5', ['6.45 15.3', '17.55 15.3']],
]
const scales = ROWS.map(([from, arcs]) => `M${from}${arcs}`)
const stalk = 'M12 5.5V2.5'

export default () => [body, ...scales, stalk]

// 实心：松果一块，三排鳞片的弧挖空，两头挖到轮廓外（鳞片一片一片分开）；果柄照旧是线
export const fill = () => [solid(body), knock(ROWS.map(([from, arcs, [a, b]]) => `M${a}L${from}${arcs}L${b}`)), stalk]
