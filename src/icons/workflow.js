import { rounded } from '../geometry'

// 工作流：左上、右下两个方块（8 × 8：3.5–11.5 / 12.5–20.5）+ 一条直角连线：从左上方块底边中点（7.5）竖直落下，拐到右下方块左边中点（16.5）
// 竖线 3.5 / 7.5 / 11.5 / 12.5 / 20.5、横线 3.5 / 11.5 / 12.5 / 16.5 / 20.5 都落在 .5 上
export default ({ radius }) => [
  rounded([[3.5, 3.5], [11.5, 3.5], [11.5, 11.5], [3.5, 11.5]], Math.min(radius, 2)),
  rounded([[12.5, 12.5], [20.5, 12.5], [20.5, 20.5], [12.5, 20.5]], Math.min(radius, 2)),
  rounded([[7.5, 11.5], [7.5, 16.5], [12.5, 16.5]], Math.min(radius, 2), false),
]
