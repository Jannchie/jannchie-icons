import { dot } from '../scene'

// Webhook：三个实心节点（上 (12, 4.5)、右下 (19.5, 17.5)、左下 (4.5, 17.5)）首尾相连成一个循环，
// 每段连线是一道向里微凹的圆弧（半径 16），三段围成弧边三角——一环扣一环地把事件传下去；
// 连线从一个节点中心画到下一个节点中心，线头收在实心点里，不会冒出来
const nodes = [[12, 4.5], [19.5, 17.5], [4.5, 17.5]]
export default () => [
  ...nodes.map((a, i) => {
    const b = nodes[(i + 1) % 3]
    return `M${a[0]} ${a[1]}A16 16 0 0 0 ${b[0]} ${b[1]}`
  }),
  ...nodes.map(([x, y]) => dot(x, y, 4.5)),
]
