import { GAP } from '../clearance'
import { bezierAt, clip } from '../clip'

// 绳结：一段软绳打的单结（椒盐卷饼的形状），两端垂下来。一笔走完：
// 左边的绳头从底下往上 → 斜着穿过中间到右上 → 绕右边的圈下来 → 沿底边横着往左 → 绕左边的圈上去 → 斜着穿过中间到右下 → 右边的绳头垂下去
// 正中的交叉点上，后一道斜线压着前一道，被压的那条断开；绳头和底边的两个交叉点太挤，断开的话底边剩不下多少，直接十字交叉
// 两个圈的外缘到 2.75 / 21.25，底边在 16.5，绳头垂到 21.25（竖线在 8.5 / 15.5）
const UP = [[8.5, 14.5], [8.5, 11.5], [12.75, 7.3], [14.75, 4.25]] // 左绳头上面那道斜线的控制点
const first = `M8.5 21.25V14.5C${UP.slice(1).map(p => p.join(' ')).join(' ')}`
const loop = 'M14.75 4.25C16 2.5 21.25 3 21.25 9C21.25 13.5 18.5 16.5 15 16.5H9C5.5 16.5 2.75 13.5 2.75 9C2.75 3 8 2.5 9.25 4.25'
const last = 'M9.25 4.25C11.25 7.3 15.5 11.5 15.5 14.5V21.25'
// 正中的交叉点：斜线上 x = 12 的那一点（左右对称，两道斜线在这里相交）；刀沿后一道斜线（前一道的镜像）的切线
let [t0, t1] = [0, 1]
for (let i = 0; i < 40; i++) {
  const t = (t0 + t1) / 2
  if (bezierAt(UP, t)[0] < 12)
    t0 = t
  else
    t1 = t
}
const [a, b] = [bezierAt(UP, t0 - 0.05), bezierAt(UP, t0 + 0.05)]
const f = v => +v.toFixed(3)
const center = `M${f(24 - a[0])} ${f(a[1])}L${f(24 - b[0])} ${f(b[1])}`

export default ({ stroke }) => [clip(first, [center], GAP + stroke), loop, last]
