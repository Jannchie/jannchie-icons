import { GAP } from '../clearance'
import { circle } from '../geometry'
import { clear, solid } from '../solid'

// 肥皂：一块花生形的皂（3.5–19.5 × 9.75–19.75：两头是半径 4 的圆角，上下两条边在正中各往里收 1，像一块收腰的香皂）
// + 骑在皂块右上角的一个大泡（圆心 (17.5, 9.75)、半径 3，皂块的轮廓在泡里断开，两个线头正好停在泡的圆上）+ 贴在大泡左上方的一个小泡
// 收腰的皂块 + 长在皂角上的泡是记号：泡泡悬在皂块上方时和皂块不相干，两个圈加一条圆角块还像一张脸；皂面不画高光、压印，干净的一块就够了
// 和按压瓶（瓶身 + 泵头）、pill（斜放的胶囊）区分开
// 皂块从右上角绕到左上角的那一大段（右边圆头 → 底边 → 左边圆头），实心版和描边版共用
const AROUND = 'A4 4 0 0 1 19.5 13.75V15.75A4 4 0 0 1 15.5 19.75C13.5 19.75 13.5 18.75 11.5 18.75C9.5 18.75 9.5 19.75 7.5 19.75A4 4 0 0 1 3.5 15.75V13.75A4 4 0 0 1 7.5 9.75'
const BAR = `M7.5 9.75C9.5 9.75 9.5 10.75 11.5 10.75C13.5 10.75 13.5 9.75 15.5 9.75${AROUND}Z`
// 描边版的皂块：同一条轮廓去掉被大泡挡住的右上角，一笔从一个断口 (19.197, 12.224) 绕到另一个断口 (14.502, 9.855)，两个断口都在大泡的圆上
const bar = `M19.197 12.224${AROUND}C9.5 9.75 9.5 10.75 11.5 10.75C13.097 10.75 13.419 10.112 14.502 9.855`
const bubbles = [circle(17.5, 9.75, 3), circle(13.5, 5.75, 1.5)]

export default () => [bar, ...bubbles]

// 实心：皂块一块；泡在前，皂块在泡四周让出缝；泡是透明的，照旧是线
export const fill = () => [solid(BAR), clear(bubbles.map(d => `${d}Z`), GAP), ...bubbles]
