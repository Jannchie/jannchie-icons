import { circle } from '../geometry'

// 奶嘴：三件——顶上的拉环（半径 2.5，底端和护片上边相切）、胶囊形护片（宽 14、高 4.5）、下面一个圆鼓的奶嘴头（颈宽 4、头半径 3）。
// 先按竖直姿态在以护片中心为原点的坐标里画，再整体放大 k 倍、顺时针转 30°、平移到 (CX, CY)；圆弧只转端点（圆弧绕自身转不变形）
const [CX, CY] = [12, 10.8]
const k = 1.15
const a = 30 * Math.PI / 180
const f = v => +v.toFixed(2)
const p = (x, y) => `${f(CX + k * (x * Math.cos(a) - y * Math.sin(a)))} ${f(CY + k * (x * Math.sin(a) + y * Math.cos(a)))}`
const [cx, cy] = p(0, -4.75).split(' ').map(Number)
export default () => [
  circle(cx, cy, 2.5 * k),
  `M${p(-4.75, -2.25)}L${p(4.75, -2.25)}A${2.25 * k} ${2.25 * k} 0 0 1 ${p(4.75, 2.25)}L${p(-4.75, 2.25)}A${2.25 * k} ${2.25 * k} 0 0 1 ${p(-4.75, -2.25)}Z`,
  `M${p(-2, 2.25)}C${p(-2, 4)} ${p(-3, 4.5)} ${p(-3, 6.5)}A${3 * k} ${3 * k} 0 0 0 ${p(3, 6.5)}C${p(3, 4.5)} ${p(2, 4)} ${p(2, 2.25)}`,
]
