import { rounded } from '../geometry'
import { stacked } from '../solid'

// 沙发（正面）：两侧扶手和座面连成一个闭合的 U 形（扶手 2.5–6.5 / 17.5–21.5，顶 10.5；座面顶 13.5，底 17.5）；
// 靠背是开放折线，两端垂直落在扶手顶边正中（x 4.5 / 19.5）；两条腿从底边垂直伸到 19.5
export default ({ radius }) => [
  rounded([[2.5, 10.5], [6.5, 10.5], [6.5, 13.5], [17.5, 13.5], [17.5, 10.5], [21.5, 10.5], [21.5, 17.5], [2.5, 17.5]], Math.min(radius, 1.5)),
  rounded([[4.5, 10.5], [4.5, 5.5], [19.5, 5.5], [19.5, 10.5]], Math.min(radius, 2), false),
  'M4.5 17.5V19.5',
  'M19.5 17.5V19.5',
]

// 实心：靠背一块（往下伸到座面顶边，藏在扶手和座面后面），扶手连座面一块在前；靠背沿扶手和座面让出 GAP 的缝，
// 前面这块是完整的 U 形，不用挖线；腿照旧是线
export const fill = ({ radius }) => {
  const seat = rounded([[2.5, 10.5], [6.5, 10.5], [6.5, 13.5], [17.5, 13.5], [17.5, 10.5], [21.5, 10.5], [21.5, 17.5], [2.5, 17.5]], Math.min(radius, 1.5))
  return [
    ...stacked(rounded([[4.5, 13.5], [4.5, 5.5], [19.5, 5.5], [19.5, 13.5]], Math.min(radius, 2)), seat),
    'M4.5 17.5V19.5',
    'M19.5 17.5V19.5',
  ]
}
