// 两层 + 贯穿的斜纹是握寿司的记号，和三层的汉堡、带切口的面包区分开
const fish = 'M2.5 12C2.5 8.75 6.5 6.5 12 6.5C17.5 6.5 21.5 8.75 21.5 12C21.5 12.85 20.85 13.5 20 13.5H4C3.15 13.5 2.5 12.85 2.5 12Z'
