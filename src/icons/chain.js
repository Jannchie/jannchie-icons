import { rounded } from '../geometry'
import { rotate } from '../transform'

// 锁链：一小段链条——两头各一节正面朝外的长圆环（7 × 9.5），中间一节侧着的链环（侧面看就是一条线，两头伸进两个环孔里各 3）；
// 竖着画（环心在 5.25 / 18.75），再顺时针转 45°：链条从右上斜到左下
// 靠「正面的环 + 侧面的环交替」认出来；link 是两个互相套住、交叉处断开的环（链接的符号），这里是三节连成一串的链条
// 都是线，没有实心版
const ring = cy => rounded([[8.5, cy - 4.75], [15.5, cy - 4.75], [15.5, cy + 4.75], [8.5, cy + 4.75]], 3.5)

export default () => [ring(5.25), ring(18.75), 'M12 7V17'].map(d => rotate(d, 45))
