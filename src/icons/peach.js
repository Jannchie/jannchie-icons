// 桃子：圆鼓鼓的果身（顶上正中一个很浅的凹口，底下是圆的）+ 果柄 + 一片朝右的叶子；
// 果缝只画上半截、偏向左边的一道浅弧，不画到底、也不放正中（正中一道通到底的缝 + 两瓣对称的果身会看成臀部）
const body = 'M12 9C12.75 8.25 14 7.75 15.5 7.75C18.5 7.75 20.5 10.5 20.5 14C20.5 18.5 16.75 21.5 12 21.5C7.25 21.5 3.5 18.5 3.5 14C3.5 10.5 5.5 7.75 8.5 7.75C10 7.75 11.25 8.25 12 9Z'
