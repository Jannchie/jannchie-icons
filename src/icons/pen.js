import { rounded } from '../geometry'
import { rotate } from '../transform'

// 笔（圆珠笔）：笔身 + 笔帽分界线 + 侧面的笔夹 + 锥形笔尖。笔夹是和铅笔（edit）区分开的关键特征。
// 先竖直画（笔尖朝下；笔身 x 8.25–13.25、y 4.25 起，笔尖 (10.75, 22.75)），再顺时针转 30°（与水平成 60°），和 edit、斜放的曲别针、纸飞机同一个角度
// 竖画时故意偏左下（笔夹在右侧），转完后墨迹上下左右居中
const r30 = d => rotate(d, 30)

export default ({ radius }) => [
  // 笔尖分界线的两端接在 y = 17.75 的两个拐角上：这两个角不做圆角（半径 0），线头正好落在顶点，不会悬在被圆角切进去的轮廓外面
  r30(rounded([[8.25, 4.25], [13.25, 4.25], [13.25, 17.75, 0], [10.75, 22.75], [8.25, 17.75, 0]], Math.min(radius, 2))),
  r30('M8.25 17.75H13.25'),
  r30('M8.25 9.25H13.25'),
  r30('M13.25 5.25H15.25V11.75'),
]
