import { petals, spiral } from '../hanamaru'

// 带茎的はなまる（老师手画的那种）：上面一朵花丸，下面一根花茎、根部左右各一片叶子；整体左右居中、上下贴 2 的边
// 花：圆心 (12, 9.6)，七瓣花瓣分界点在半径 6 的圆上，瓣尖外缘固定在半径 7.6（顶 2，线宽变粗往里长）；
// 位置比 hanamaru 小，漩涡只绕一圈半（半径每半圈加 1.15，相邻两圈中心线间距 2.3），粗字重下和花瓣之间还留得出缝
// 花茎从花底下的分界点（y 15.6）垂到底边（墨迹到 22）；两片叶子从茎底往左右上方伸出，叶尖在 x 5.5 / 18.5、y 18
export default ({ stroke }) => {
  const h = stroke / 2
  const [cy, b] = [9.6, 22 - h]
  return [
    petals(12, cy, 7, 6, 7.6 - h),
    spiral(12, cy, 1.15, 3),
    `M12 ${cy + 6}V${b}`,
    `M12 ${b}C10.5 18.5 8.5 17.5 5.5 18C6.5 20.5 9 ${b} 12 ${b}Z`,
    `M12 ${b}C13.5 18.5 15.5 17.5 18.5 18C17.5 20.5 15 ${b} 12 ${b}Z`,
  ]
}
