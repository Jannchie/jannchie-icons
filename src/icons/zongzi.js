import { through } from '../geometry'
import { knock, solid } from '../solid'

// 粽子：粽叶包成的鼓鼓的三角（三条边都往外微鼓，3.25–20.75 × 3.5–20.1，角圆）+ 从顶上斜到底边的一道粽叶折边（偏左，叶子是斜着裹的）
// + 拦腰捆的一道绳（13.5，两头落在两条斜边上）。斜的折边 + 横着捆的绳是记号：像一个捆好的叶包，
// 和底下贴一块海苔的饭团、正中一道竖棱的金字塔区分开
const body = 'M10.5 4.5C11.25 3.25 12.75 3.25 13.5 4.5C16 8.5 18.75 12.5 20.75 16.75C21.5 18.25 20.75 19.5 19 19.75C14.25 20.25 9.75 20.25 5 19.75C3.25 19.5 2.5 18.25 3.25 16.75C5.25 12.5 8 8.5 10.5 4.5Z'
// 折边：上端在顶弧的正中，下端在底弧上
const FOLD = [[12, 3.56], [9, 20.05]]
// 绳：两头是斜边在 y = 13.5 处的点
const [l, r] = [5.2, 18.8]

export default () => [body, through(...FOLD, 0), `M${l} 13.5H${r}`]

// 实心：粽子一块，折边和绳都挖穿（两头穿出轮廓），分成四片叶面
export const fill = ({ stroke }) => [
  solid(body),
  knock([through(...FOLD, stroke * 2), `M${l - stroke * 2} 13.5H${r + stroke * 2}`]),
]
