import { circle } from '../geometry'
import { body, track } from '../tank'

// 自行高炮：履带 + 车体（顶边 12.5，高 3）+ 梯形炮塔（7.5–15 / 6.5–16，顶边 8.5，高 4：炮管框的下角离车体顶边还有 2.4）；
// 双联炮管：两根平行的直线，从炮塔前斜面（(15, 8.5)–(16, 12.5)）上伸出，以 50° 仰角指向右上——
// 上管从炮塔前上角出发，下管从斜面上 y 11.5 处出发，两管中心线相距约 2.4，粗字重下也分得开；长 7，管口在 (19.5, 3.14) / (20.25, 6.14)；
// 炮塔顶后部一根竖直杆托着一个小圆盘雷达（圆心 (9.5, 4.25)、半径 1.75：圆顶粗字重下离上缘 1.5，圆底离炮塔顶 2.5，粗字重下杆还露出一截）
const u = [Math.cos(50 * Math.PI / 180), -Math.sin(50 * Math.PI / 180)] // 炮管方向
const barrel = ([x, y], len) => `M${x} ${y}L${+(x + u[0] * len).toFixed(3)} ${+(y + u[1] * len).toFixed(3)}`
export default ({ radius }) => [
  ...track(3, 21, 5),
  body([[5.5, 15.5], [4, 12.5], [19.5, 12.5], [18.5, 15.5]], radius),
  body([[6.5, 12.5], [7.5, 8.5], [15, 8.5, 0], [16, 12.5]], radius),
  barrel([15, 8.5], 7),
  barrel([15.75, 11.5], 7),
  'M9.5 8.5V6',
  circle(9.5, 4.25, 1.75),
]
