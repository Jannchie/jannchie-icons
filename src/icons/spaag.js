import { circle, rounded } from '../geometry'
import { body, track } from '../tank'

// 自行高炮：履带 + 车体（顶边 12.5，高 3）+ 梯形炮塔（顶边 7.5，高 5：炮管框的下角离车体够远）；
// 双联炮管画成一个闭合的细长框（宽 2.5、长 7）：两条长边就是两根炮管，框的后下角压在炮塔前上角（硬棱）上，以 50° 仰角指向右上——
// 闭合的框没有线头，两根管之间的缝在粗字重下也留得出来；框压在硬棱上的那个角也是硬棱（圆角会让它离开炮塔、挤出一道窄缝）；
// 炮塔顶后部一根竖直杆托着一个小圆盘雷达（圆盘底离炮塔顶 3）
const [cx, cy] = [14.75, 7.5]
const u = [Math.cos(50 * Math.PI / 180), -Math.sin(50 * Math.PI / 180)] // 炮管方向
const n = [-u[1], u[0]] // 垂直于炮管、朝右下
const at = (s, t) => [cx + u[0] * s + n[0] * t, cy + u[1] * s + n[1] * t]
export default ({ radius }) => [
  ...track(3, 21, 5),
  body([[5.5, 15.5], [4, 12.5], [19.5, 12.5], [18.5, 15.5]], radius),
  body([[6.5, 12.5], [7.75, 7.5], [14.75, 7.5, 0], [16, 12.5]], radius),
  rounded([[...at(0, 0), 0], at(7, 0), at(7, 2.5), at(0, 2.5)], Math.min(radius, 0.5)),
  'M9.5 7.5V4.5',
  circle(9.5, 2.75, 1.75),
]
