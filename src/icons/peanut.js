import { knock, solid } from '../solid'
import { rotate } from '../transform'

// 花生（带壳）：一颗斜 45° 的 8 字形花生壳（左下一头大、右上一头略小，中间收腰）+ 壳上的网纹：两道顺着壳的长纹 + 四道横纹（细节线）。先横着画，再逆时针转 45°
// 横着画时：左边的鼓包 0.5–11 × 6.75–17.25，右边的鼓包 13–23.25 × 7.25–16.75，腰在 x = 12.5（8.5–15.5）
// 8 字形 + 网纹是花生的记号：和收腰但光面带泡泡的 soap、两头圆的 pill 区分开
const tilt = d => rotate(d, -45)
const shell = tilt('M0.5 12C0.5 9.53 3.28 6.75 5.75 6.75C8.07 6.75 10.18 8.5 12.5 8.5C14.54 8.5 16.46 7.25 18.5 7.25C20.74 7.25 23.25 9.76 23.25 12C23.25 14.24 20.74 16.75 18.5 16.75C16.46 16.75 14.54 15.5 12.5 15.5C10.18 15.5 8.07 17.25 5.75 17.25C3.28 17.25 0.5 14.47 0.5 12Z')
// 网纹：长纹两头不到壳的两端，横纹两头落在壳的轮廓上
const net = [
  'M3.5 10.25C6.5 8.75 9.5 10.75 12.5 10.75C15.5 10.75 17.75 9.25 20 10.1',
  'M3.5 13.75C6.5 15.25 9.5 13.25 12.5 13.25C15.5 13.25 17.75 14.75 20 13.9',
  'M5.5 6.75V17.25',
  'M9.25 7.6V16.4',
  'M15.75 7.75V16.25',
  'M19 7.25V16.75',
].map(d => ({ d: tilt(d), detail: true }))

// 实心版用的壳纹：五道顺着壳的短划，交错排开
const dashes = ['M3.5 10.5H6.5', 'M5 13.5H8', 'M10.75 12H14.25', 'M16.5 10.75H19.5', 'M15.5 13.5H18.5'].map(d => ({ d: tilt(d), detail: true }))

export default () => [shell, ...net]

// 实心：花生壳一块，壳纹换成几道挖空的短划（整张网挖空的话壳被切成十几块碎片）
export const fill = () => [solid(shell), knock(dashes)]
