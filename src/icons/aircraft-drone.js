import { rounded } from '../geometry'
import { dot } from '../scene'

// 无人机（俯视四旋翼，没有朝向）：中间一个圆角方块机身（9.5–14.5），四根斜向机臂从机身伸到四个电机 (6.5, 6.5) 等（桨叶横线落在 .5 上）；
// 每个电机上一根横放的两叶螺旋桨（长 8，2.5–10.5 等）和一个桨毂实心点。不画护圈：圆圈 + 横线读起来像「⊖」，不像螺旋桨
export default ({ radius }) => [
  rounded([[9.5, 9.5], [14.5, 9.5], [14.5, 14.5], [9.5, 14.5]], Math.min(radius, 1.5)),
  ...[[6.5, 6.5], [17.5, 6.5], [6.5, 17.5], [17.5, 17.5]].flatMap(([x, y]) => {
    const [sx, sy] = [Math.sign(12 - x), Math.sign(12 - y)]
    return [`M${x} ${y}L${12 - sx * 2.5} ${12 - sy * 2.5}`, `M${x - 4} ${y}H${x + 4}`, dot(x, y, 2.5)]
  }),
]
