import { crisp, rounded, circle } from '../geometry'
import { dot } from '../scene'

// 黑胶唱片机（俯视）：横向的圆角机身（2.5–21.5 × 4.5–19.5）+ 左边一张唱片（圆心 (10, 12)、半径 5.5，离机身边都留 2）+ 中心轴
// 右上角是唱臂支点（实心点 (18.5, 7.5)，唱臂从点里出发，线头藏在点里），唱臂竖直落下再斜折进唱片，唱头落在 (13.5, 15)，离唱片外圈约 1.6
export default ({ radius }) => [
  rounded([[2.5, 4.5], [21.5, 4.5], [21.5, 19.5], [2.5, 19.5]], Math.min(radius, 2.5)),
  circle(10, 12, 5.5),
  dot(10, 12),
  dot(18.5, 7.5, 3),
  rounded([[18.5, 7.5], [18.5, 13], [13.5, 15]], crisp(radius), false),
]
