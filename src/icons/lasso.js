import { circle } from '../geometry'

// 套索（套索选区工具）：一个扁圆的虚线绳圈（圆心 (12, 9.5)、半径 9 × 6，七段虚线）+ 打在绳圈左下的绳结（小圆，半径 1.75，圆心就在绳圈的椭圆上）
// + 从绳结往下甩出去的一段绳尾。虚线是「选区」的记号，和实线的对话气泡、气球区分开
// 都是线，没有实心版
const [cx, cy, rx, ry] = [12, 9.5, 9, 6]
const KNOT = 130 // 绳结在椭圆上的参数角
const f = v => +v.toFixed(3)
const on = deg => [f(cx + rx * Math.cos(deg * Math.PI / 180)), f(cy + ry * Math.sin(deg * Math.PI / 180))]
// 七段虚线各自的起止参数角：按弧长等分（每段长 2.94、段间留 3，绳结两边各让出 4.5——粗字重下虚线也不碰绳结），所以角度不等距——椭圆两头走得慢
const DASHES = [[166.9, 194.7], [220.1, 241.4], [261.1, 279.9], [299.6, 321.1], [346.7, 374.4], [399.9, 421.2], [440.9, 459.7]]
const [kx, ky] = on(KNOT)

export default () => [
  ...DASHES.map(([a, b]) => `M${on(a).join(' ')}A${rx} ${ry} 0 0 1 ${on(b).join(' ')}`),
  circle(kx, ky, 1.75),
  `M${kx} ${f(ky + 1.75)}C${kx} ${f(ky + 3.75)} ${f(kx - 1)} ${f(ky + 5.75)} ${f(kx - 2.75)} ${f(ky + 6.75)}`,
]
