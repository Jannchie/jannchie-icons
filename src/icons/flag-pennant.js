import { crisp, rounded } from '../geometry'

// 三角小旗：闭合的三角旗面（左边 5.5，3.5–12.5，尖在 (17.5, 8)，尖角 41°）+ 旗杆从旗面左下角往下接到 21
// 尖角不随全局圆角变圆；尖角模式下尖会被斜接上限切成一个很小的平头
// 旗面左边两个角不随全局圆角：旗杆的线头正好落在左下角上，角被圆角切掉时线头会被端点吸附拉歪
export default ({ radius }) => [
  rounded([[5.5, 3.5, 0], [17.5, 8, crisp(radius)], [5.5, 12.5, 0]], Math.min(radius, 1)),
  'M5.5 12.5V21',
]
