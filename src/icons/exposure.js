import { rounded } from '../geometry'

// 曝光：方框被 \ 对角线分开（对角线统一左上 → 右下），右上加号、左下减号
// 对角线的两端落在框的圆角上：圆角半径 c 时，圆角弧和对角线的交点离框角 c(1 - 1/√2)，尖角模式下就是框角
export default ({ radius }) => {
  const c = Math.min(radius, 2.5)
  const e = Math.round((3.5 + c * (1 - Math.SQRT1_2)) * 1000) / 1000
  const f = 24 - e
  return [
    rounded([[3.5, 3.5], [20.5, 3.5], [20.5, 20.5], [3.5, 20.5]], c),
    `M${e} ${e}L${f} ${f}`,
    // 加号中心 (16.5, 7.5)、减号中心 (7.5, 16.5)，关于对角线对称，横竖笔都在 .5 上
    'M16.5 5.25V9.75',
    'M14.25 7.5H18.75',
    'M5.25 16.5H9.75',
  ]
}
