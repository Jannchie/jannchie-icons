import { rounded } from '../geometry'
import { knock, solid } from '../solid'

// 口琴（半音阶）：长方琴身 + 上方盖板线 + 一排吹孔 + 右侧推键
// 吹孔是一排竖着的短槽（像真口琴的方孔），5 个、间距 3，竖边落在 .5 上（5.5–17.5，连同右边的推键整体居中）；
// 槽长 0.5，加上圆头约 2 高；盖板线提到 10.5，槽落在盖板线和琴身底边之间的正中（13.25），粗字重下上下也各留 0.5；
// 推键在吹孔这一排的高度（13.5），离盖板线够远
const HOLES = [5.5, 8.5, 11.5, 14.5, 17.5].map(x => `M${x} 13V13.5`)
export default ({ radius }) => [
  // 琴身 8–16
  rounded([[2.5, 8], [19.5, 8], [19.5, 16], [2.5, 16]], Math.min(radius, 1.5)),
  'M2.5 10.5H19.5',
  ...HOLES,
  'M19.5 13.5H21.5',
]

// 实心：琴身一块，盖板线、吹孔挖空；推键照旧是线
export const fill = ({ radius, stroke }) => [
  solid(rounded([[2.5, 8], [19.5, 8], [19.5, 16], [2.5, 16]], Math.min(radius, 1.5))),
  knock([`M${2.5 - stroke} 10.5H${19.5 + stroke}`, ...HOLES]),
  'M19.5 13.5H21.5',
]
