// 当前语言：App 负责从本地存储恢复、写回
export const locale = ref('en')

const lookup = (lang, key) => key.split('.').reduce((o, k) => o?.[k], messages[lang])

// t('ui.empty', { q }) → 按当前语言取词，缺词回退英语，再缺就原样返回 key；{name} 占位替换成参数
export function t(key, params = {}) {
  const text = lookup(locale.value, key) ?? lookup('en', key) ?? key
  return text.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '')
}

// 搜索分类名时，当前语言和英语都能搜到
export const searchTitle = id => `${t(`cat.${id}`)} ${lookup('en', `cat.${id}`)}`
