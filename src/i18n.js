// 当前语言：App 负责从本地存储恢复、写回
export const locale = ref('en')

const lookup = (lang, key) => key.split('.').reduce((o, k) => o?.[k], messages[lang])

// t('ui.empty', { q }) → 按当前语言取词，缺词回退英语，再缺就原样返回 key；{name} 占位替换成参数
export function t(key, params = {}) {
  const text = lookup(locale.value, key) ?? lookup('en', key) ?? key
  return text.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '')
}

// 搜索时分类名、小节名用所有语言的叫法拼起来：不管界面是什么语言，英、中、日都能搜到
// 词表是静态的：每个 key 拼一次、转好小写就缓存起来，搜索时每次按键不用再对每个图标重新拼
const searchCache = new Map()
function allLangs(key) {
  let text = searchCache.get(key)
  if (text === undefined) {
    text = LOCALES.map(l => lookup(l.id, key)).filter(Boolean).join(' ').toLowerCase()
    searchCache.set(key, text)
  }
  return text
}
export const searchTitle = id => allLangs(`cat.${id}`)
export const searchGroupTitle = key => allLangs(`group.${key}`)
